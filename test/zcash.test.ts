// Controlled structural examples: zero signatures/proofs, never valid or mined transactions.
function le(n: bigint, size: number): Uint8Array { const b=new Uint8Array(size); for(let i=0;i<size;i++){b[i]=Number(n&255n);n>>=8n;}return b; }
function concat(...parts:Uint8Array[]):Uint8Array{const b=new Uint8Array(parts.reduce((n,p)=>n+p.length,0));let offset=0;for(const p of parts){b.set(p,offset);offset+=p.length;}return b;}
function syntheticV4(prevId:string,scriptHex:string,shield=false): {txid:string;hex:string} {
  const input=concat(bytesOf(prevId).reverse(),le(0n,4),new Uint8Array([0]),le(0xffffffffn,4));
  const script=bytesOf(scriptHex);
  const output=concat(le(100000000n,8),new Uint8Array([script.length]),script);
  const body=concat(bytesOf('0400008085202f89'),new Uint8Array([1]),input,new Uint8Array([shield?0:1]),...(shield?[]:[output]),new Uint8Array(8),le(shield?((1n<<64n)-100000000n):0n,8),new Uint8Array([0,shield?1:0]),...(shield?[new Uint8Array(948)]:[]),new Uint8Array([0]),...(shield?[new Uint8Array(64)]:[]));
  const hex=hexOf(body);return {hex,txid:decodeZcashTransaction(hex,'mainnet').txid};
}
function syntheticBundle(change=false,missing=false) {
  const source=syntheticV4('aa'.repeat(32),'76a914'+'11'.repeat(20)+'88ac');
  const shield=syntheticV4(source.txid,'76a914'+'11'.repeat(20)+'88ac',true);
  const refund=syntheticV4('bb'.repeat(32),'76a914'+(change?'22':'11').repeat(20)+'88ac');
  const refundTo=decodeZcashTransaction(refund.hex,'mainnet').outputs[0]!.address!;
  return {format:'veylens-zcash-evidence/1',network:'mainnet',transactions:missing?[shield,refund]:[source,shield,refund],shieldingTxid:shield.txid,refundTxid:refund.txid,refundTo};
}
